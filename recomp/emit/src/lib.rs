#[inline(always)]
fn mask(n: u32) -> u64 { if n >= 8 { u64::MAX } else { (1u64 << (n * 8)) - 1 } }
#[inline(always)]
fn sx(v: u64, n: u32) -> u64 { let s = 64 - n * 8; (((v << s) as i64) >> s) as u64 }
#[inline(always)]
fn sign(v: u64, n: u32) -> bool { (v >> (n * 8 - 1)) & 1 == 1 }
#[inline(always)]
unsafe fn ld(a: u64, n: u32) -> u64 {
    unsafe {
        match n {
            1 => (a as *const u8).read_unaligned() as u64,
            2 => (a as *const u16).read_unaligned() as u64,
            4 => (a as *const u32).read_unaligned() as u64,
            _ => (a as *const u64).read_unaligned(),
        }
    }
}
#[inline(always)]
unsafe fn st(a: u64, n: u32, v: u64) {
    unsafe {
        match n {
            1 => (a as *mut u8).write_unaligned(v as u8),
            2 => (a as *mut u16).write_unaligned(v as u16),
            4 => (a as *mut u32).write_unaligned(v as u32),
            _ => (a as *mut u64).write_unaligned(v),
        }
    }
}
#[inline(always)]
fn wr(c: &mut Ctx, r: usize, n: u32, v: u64) {
    match n {
        8 => c.r[r] = v,
        4 => c.r[r] = v & 0xffff_ffff,
        _ => { let m = mask(n); c.r[r] = (c.r[r] & !m) | (v & m); }
    }
}
#[inline(always)]
fn szf(c: &mut Ctx, r: u64, n: u32) { c.zf = r & mask(n) == 0; c.sf = sign(r, n); }
type Y = [u64; 4];
#[inline(always)]
unsafe fn vld(a: u64, n: usize) -> Y {
    let mut y = [0u64; 4];
    unsafe { core::ptr::copy_nonoverlapping(a as *const u8, y.as_mut_ptr() as *mut u8, n) };
    y
}
#[inline(always)]
unsafe fn vst(a: u64, n: usize, y: Y) {
    unsafe { core::ptr::copy_nonoverlapping(y.as_ptr() as *const u8, a as *mut u8, n) };
}
/// A VEX write of `w` bytes: the rest of the ymm register is cleared.
#[inline(always)]
fn vset(c: &mut Ctx, d: usize, w: usize, y: Y) {
    let mut v = y;
    if w <= 16 { v[2] = 0; v[3] = 0; }
    c.x[d] = v;
}
